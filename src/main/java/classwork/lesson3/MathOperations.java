package classwork.lesson3;

public class MathOperations {

    public static void main(String[] args) {

        float a = 19;
        float b = 6;

        System.out.println("a + b = " + (a + b));
        System.out.println("a - b = " + (a - b));
        System.out.println("a * b = " + (a * b));
        System.out.println("a / b = " + (a / b));
        System.out.println("a % b = " + (a % b));
        System.out.println("a++ = " + (a++));
        System.out.println("--b = " + (--b));

    }

}
